import test from "node:test";
import assert from "node:assert/strict";
import { cpSync, mkdtempSync, readFileSync, writeFileSync, existsSync, rmSync, mkdirSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { parseBody, plain } from "../src/parse.mjs";
import { loadProject } from "../src/project.mjs";
import { renderMarkdown, diffMarkdown, writeMarkdown } from "../src/build-md.mjs";
import { buildSite } from "../src/build-site.mjs";
import { texWriter, texEscape } from "../src/write-tex.mjs";

const fixture = join(dirname(fileURLToPath(import.meta.url)), "fixture");
const copy = () => { const d = mkdtempSync(join(tmpdir(), "jpdocs-")); cpSync(fixture, d, { recursive: true }); return d; };
const load = (d) => loadProject(join(d, "docs.config.json"));

test("parser: directives, wiki links, fence options", () => {
  const t = parseBody(":::warning Title\nBody [[a#b|text]] [[term:X]]\n\n```sh title=\"T\"\nx\n```\n:::\n\n::graphic rule/end Alt text\n");
  assert.equal(t[0].type, "callout"); assert.equal(t[0].kind, "warning"); assert.equal(t[0].title, "Title");
  const para = t[0].children[0].children; assert.deepEqual(para.filter((n) => n.type === "xref").map((n) => [n.id, n.anchor, n.text]), [["a", "b", "text"]]);
  assert.equal(para.find((n) => n.type === "term").key, "x");
  assert.deepEqual([t[0].children[1].lang, t[0].children[1].title], ["sh", "T"]);
  assert.deepEqual([t[1].type, t[1].ref, t[1].alt], ["graphic", "rule/end", "Alt text"]);
});
test("parser: nested containers and unclosed", () => {
  const t = parseBody("::::note\n:::tip\nin\n:::\n::::\n\n:::danger\nopen");
  assert.equal(t[0].children[0].type, "callout"); assert.equal(t[1].unclosed, true);
});
test("parser: heading ids dedupe", () => { const t = parseBody("## A b\n\n## A b\n"); assert.deepEqual(t.map((h) => h.id), ["a-b", "a-b-1"]); assert.equal(plain(t[0].children), "A b"); });

test("fixture is valid", () => { const p = load(copy()); assert.deepEqual(p.errors, []); assert.equal(p.pages.length, 3); });

test("check: reports clear errors", () => {
  const d = copy();
  writeFileSync(join(d, "docs-src/bad.md"), "---\nsummary: x\nsection: nope\nicon: not-an-icon\n---\n\n# H1\n\n#### skip\n\n[[missing]] [[one#nope]] [x](gone.md) [[term:Nope]]\n\n::graphic spot/not-a-real-graphic\n\n:::oops\nx\n:::\n\n```\nplain\n```\n\n<b>html</b>\n");
  const p = load(d); const e = p.errors.join("\n");
  for (const want of ["title is required", 'unknown section "nope"', 'unknown icon "not-an-icon"', "start the body at ##", "skips from", 'unknown page "missing"', 'no heading anchor "#nope"', "gone.md: no such page", 'unknown glossary term "Nope"', 'unknown graphic "spot/not-a-real-graphic"', 'unknown directive "oops"', "raw HTML"]) assert.ok(e.includes(want), `missing: ${want}\n${e}`);
  assert.match(p.errors[0], /^docs-src\/bad\.md:\d+: /);
  assert.ok(p.warnings.join("\n").includes("without a language"));
});

test("markdown writer: GFM output and round trip", () => {
  const d = copy(); const p = load(d); const out = renderMarkdown(p);
  const one = out.get("docs/one.md");
  assert.ok(one.startsWith("<!-- Generated by jupiter-docs from docs-src/one.md."));
  assert.ok(one.includes("> [!WARNING]\n> **Careful**"));
  assert.ok(one.includes("[link](sub/two.md#details)") && one.includes("[Widget](sub/two.md#term-widget)"));
  assert.ok(one.includes("| b\\|c | 2 |") && one.includes("| :--- | ---: |"));
  assert.ok(one.includes("<picture>") && one.includes("rule-end-dark.svg"));
  assert.ok(out.has("docs/README.md"));
  // parse(render(x)) keeps the same shape: re-render the generated file as a source page and compare block types
  const body = one.split("\n").slice(4).join("\n");
  const again = parseBody(body).map((n) => n.type).join(",");
  assert.ok(again.startsWith("paragraph,heading,list,list,quote,table"), again);
});
test("stale check: missing, edited, orphaned, hand-written files untouched", () => {
  const d = copy(); let p = load(d);
  assert.ok(diffMarkdown(p).every((s) => s.endsWith("missing")));
  writeMarkdown(p); assert.deepEqual(diffMarkdown(p), []);
  writeFileSync(join(d, "docs/hand.md"), "# hand written\n"); assert.deepEqual(diffMarkdown(p), []);
  writeFileSync(join(d, "docs/one.md"), readFileSync(join(d, "docs/one.md"), "utf8") + "\nedit\n"); assert.deepEqual(diffMarkdown(p), ["docs/one.md: out of date"]);
  writeMarkdown(p); rmSync(join(d, "docs-src/sub/two.md"));
  writeFileSync(join(d, "docs-src/one.md"), readFileSync(join(d, "docs-src/one.md"), "utf8").replace(/\[\[sub\/two#details\|link\]\]/, "x").replace("- [[sub/two]]", "- none"));
  p = load(d); assert.ok(diffMarkdown(p).some((s) => s.includes("sub/two.md: generated file with no source")));
  assert.ok(existsSync(join(d, "docs/hand.md")));
});

test("site: pages, relative links, search index, hashed assets, 404", async () => {
  const d = copy(); const p = load(d); await buildSite(p); const s = join(d, "dist/site");
  const one = readFileSync(join(s, "one/index.html"), "utf8");
  assert.ok(one.includes('href="../sub/two/#details"') && one.includes('href="../assets/docs.'));
  assert.ok(one.includes('class="jp-callout jp-callout--warn"') && one.includes('<a class="skip') === false);
  assert.ok(one.includes('href="#main"') && one.includes("<main") && one.includes('aria-label="Breadcrumb"') && one.includes('rel="next"'));
  assert.ok(one.includes("&lt;area&gt;") && !one.includes("<area>"));
  const home = readFileSync(join(s, "index.html"), "utf8"); assert.ok(home.includes('href="one/"'));
  const four = readFileSync(join(s, "404.html"), "utf8"); assert.ok(four.includes('href="/assets/docs.'));
  assert.match(readFileSync(join(s, "_headers"), "utf8"), /\/assets\/\*\n {2}Cache-Control: public, max-age=31536000, immutable/);
  const idx = JSON.parse(readFileSync(join(s, one.match(/data-search="\.\.\/(assets\/search\.[0-9a-f]+\.json)"/)[1]), "utf8")); assert.equal(idx.length, 3);
  assert.ok(!existsSync(join(s, "sitemap.xml")));
});
test("site: base path in headers and sitemap", async () => {
  const d = copy(); const cfg = JSON.parse(readFileSync(join(d, "docs.config.json"), "utf8")); cfg.base = "/docs/"; cfg.siteUrl = "https://x.test"; writeFileSync(join(d, "docs.config.json"), JSON.stringify(cfg));
  await buildSite(load(d)); const s = join(d, "dist/site");
  assert.ok(readFileSync(join(s, "_headers"), "utf8").startsWith("/docs/assets/*"));
  assert.ok(readFileSync(join(s, "sitemap.xml"), "utf8").includes("<loc>https://x.test/docs/one/</loc>"));
  assert.ok(readFileSync(join(s, "404.html"), "utf8").includes('href="/docs/assets/docs.'));
});

test("tex writer: semantic macros only, escaping", () => {
  const p = load(copy()); const w = texWriter({ pages: p.pages, config: p.config }); const t = w.document({ nav: p.nav, date: "1 Jan 2026", version: "v9" });
  for (const want of ["\\documentclass{jupiter-docs}", "\\jpdocsection{Alpha}{First.}", "\\jppage{page:one}{One}{The first page.}", "\\begin{jpcallout}[warn]{Careful}", "\\begin{jpdocscode}", "\\begin{jptable}{lr}", "\\jpgraphic{rule}{end}{}", "\\hyperlink{h:sub-two:details}{link}", "\\jpterm{Widget}", "$(gh auth token)".replace(/[$]/, "\\$"), "99.98\\%", "a\\_b", "\\textbackslash{}", "b|c"]) assert.ok(t.includes(want), `missing ${want}`);
  assert.ok(!/\\(color|fontsize|vspace|rule|hspace)/.test(t.replace(/\\jp\w+/g, "")), "writer must not emit visual commands");
  assert.equal(texEscape("a & b # c"), "a \\& b \\# c");
});
