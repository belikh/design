// AST -> GitHub-flavoured Markdown (plain GFM: callouts are GitHub alerts, graphics are <picture>, page links are relative .md links).
import { posix } from "node:path";
import { CALLOUTS } from "./spec.mjs";
import { plain, slug } from "./parse.mjs";

export const MARKER = "Generated by jupiter-docs";
export const mdPath = (id) => (id === "index" ? "README.md" : `${id}.md`);
const WIDTH = { icon: "32", spot: "200", scene: "480", rule: "50%" };

function escText(s, inTable) {
  let t = s.replace(/\\/g, "\\\\").replace(/([`*\[\]])/g, "\\$1").replace(/<(?=[A-Za-z\/!?])/g, "\\<").replace(/(^|[^\p{L}\p{N}])_|_(?=$|[^\p{L}\p{N}])/gu, (m) => m.replace("_", "\\_")).replace(/&(?=#?\w+;)/g, "&amp;");
  if (inTable) t = t.replace(/\|/g, "\\|");
  return t;
}
const fenceFor = (text, ch) => ch.repeat(Math.max(3, ...[...text.matchAll(new RegExp(`${ch === "`" ? "`" : "~"}+`, "g"))].map((m) => m[0].length + 1)));

export function mdWriter({ pages, config, graphicUrl }) {
  const byId = new Map(pages.map((p) => [p.id, p]));
  const inl = (nodes, page, tbl) => nodes.map((n) => {
    switch (n.type) {
      case "text": return escText(n.value, tbl);
      case "code": { const f = fenceFor(n.value, "`").slice(2) || "`"; const pad = /^`|`$/.test(n.value) ? " " : ""; return `${f}${pad}${tbl ? n.value.replace(/\|/g, "\\|") : n.value}${pad}${f}`; }
      case "em": return `*${inl(n.children, page, tbl)}*`;
      case "strong": return `**${inl(n.children, page, tbl)}**`;
      case "del": return `~~${inl(n.children, page, tbl)}~~`;
      case "softbreak": return tbl ? " " : "\n";
      case "hardbreak": return tbl ? " " : "\\\n";
      case "link": return `[${inl(n.children, page, tbl)}](${n.href.replace(/[() ]/g, (c) => encodeURIComponent(c))}${n.title ? ` "${n.title.replace(/"/g, '\\"')}"` : ""})`;
      case "image": return `![${escText(n.alt)}](${n.src.replace(/[() ]/g, (c) => encodeURIComponent(c))})`;
      case "xref": {
        const t = byId.get(n.id); const rel = posix.relative(posix.dirname(mdPath(page.id)), mdPath(n.id)); const text = n.children ? inl(n.children, page, tbl) : escText(n.text || t?.meta.title || n.id, tbl);
        return `[${text}](${rel}${n.anchor ? `#${n.anchor}` : ""})`;
      }
      case "term": { const gp = pages.find((p) => p.tree.some((b) => b.type === "glossary")); if (!gp) return escText(n.text); return `[${escText(n.text)}](${posix.relative(posix.dirname(mdPath(page.id)), mdPath(gp.id))}#term-${slug(n.key)})`; }
      default: return "";
    }
  }).join("");
  const indent = (s, first, rest) => s.split("\n").map((l, i) => (i === 0 ? first : l ? rest : "") + (i === 0 || l ? l : "")).join("\n");
  const prefix = (s, p) => s.split("\n").map((l) => (l ? p + l : p.trimEnd())).join("\n");
  const blk = (nodes, page, tight = false) => nodes.map((n) => one(n, page)).filter((x) => x !== null).join(tight ? "\n" : "\n\n");
  function one(n, page) {
    switch (n.type) {
      case "heading": return `${"#".repeat(n.depth)} ${inl(n.children, page)}`;
      case "paragraph": { let t = inl(n.children, page); t = t.replace(/^(#{1,6}\s|[-+>]\s|\d+[.)]\s|={3,}|-{3,})/, "\\$1"); return t; }
      case "list": return n.items.map((it, i) => { const m = n.ordered ? `${n.start + i}. ` : "- "; return indent(blk(it, page, n.tight), m, " ".repeat(m.length)); }).join(n.tight ? "\n" : "\n\n");
      case "quote": return prefix(blk(n.children, page), "> ");
      case "codeblock": { const f = fenceFor(n.text, "`"); return `${n.title ? `**${escText(n.title)}**\n\n` : ""}${f}${n.lang}\n${n.text}\n${f}`; }
      case "hr": return "---";
      case "table": {
        const row = (cells) => `| ${cells.map((c) => inl(c, page, true)).join(" | ")} |`;
        const sep = n.align.map((a) => (a === "left" ? ":---" : a === "center" ? ":---:" : a === "right" ? "---:" : "---"));
        return [row(n.head), `| ${sep.join(" | ")} |`, ...n.rows.map(row)].join("\n");
      }
      case "callout": {
        const c = CALLOUTS[n.kind]; const body = blk(n.children, page); const title = n.title ? `**${escText(n.title)}**\n\n` : "";
        return prefix(`[!${c.gh}]\n${title}${body}`, "> ");
      }
      case "seealso": return `**See also**\n\n${blk(n.children, page)}`;
      case "graphic": {
        const [tier] = n.ref.split("/"); const alt = (n.alt || "").replace(/"/g, "&quot;");
        const u = (theme) => graphicUrl(n.ref, theme, page);
        return `<p align="center"><picture><source media="(prefers-color-scheme: dark)" srcset="${u("dark")}"><img alt="${alt}" src="${u("light")}" width="${WIDTH[tier] ?? "200"}"></picture></p>`;
      }
      case "glossary": return Object.entries(config.glossary).sort(([a], [b]) => a.localeCompare(b)).map(([k, v]) => `- <a id="term-${slug(k)}"></a>**${escText(k)}**: ${escText(v)}`).join("\n");
      default: return null;
    }
  }
  return {
    file: (page) => mdPath(page.id),
    render(page) {
      const src = `${page.file}`;
      return `<!-- ${MARKER} from ${src}. Do not edit; change the source and run jupiter-docs build. -->\n\n# ${escText(page.meta.title)}\n\n${blk(page.tree, page)}\n`;
    },
  };
}

export function graphicUrlFor(config, mdOutDir) {
  return (ref, theme, page) => {
    const [tier, name] = ref.split("/"); const dir = posix.dirname(mdPath(page.id)); const out = posix.join(mdOutDir, dir);
    const root = posix.relative(out, ".") || ""; const up = root ? `${root}/` : "";
    return config.graphicsUrl.replace("{root}", up).replace("{tier}", tier).replace("{name}", name).replace("{theme}", theme);
  };
}
