// Embeds the owner's logo (packages/graphics/logo/jupiter-logo-{light,dark}.svg, outlined from SGI Alt 700) into src/logo.mjs so
// render.mjs stays dependency-free and a packed jupiter-github.tgz needs nothing from the graphics package. The logo is never redrawn here.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
const here = dirname(fileURLToPath(import.meta.url));
const out = {};
for (const s of ["light", "dark"]) {
  const svg = readFileSync(join(here, "../../graphics/logo", `jupiter-logo-${s}.svg`), "utf8").trim();
  const m = /^<svg [^>]*viewBox="([^"]+)"[^>]*>([\s\S]*)<\/svg>$/.exec(svg);
  if (!m) throw new Error(`unexpected logo svg: ${s}`);
  const [, vb, inner] = m; const [, , w, h] = vb.split(" ").map(Number);
  out[s] = { viewBox: vb, w, h, inner };
}
writeFileSync(join(here, "../src/logo.mjs"), `// Generated by scripts/sync-logo.mjs from packages/graphics/logo. Do not edit by hand.\nexport const LOGO = ${JSON.stringify(out)};\n`);
console.log("packages/github/src/logo.mjs");
