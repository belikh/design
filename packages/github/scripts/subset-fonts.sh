#!/usr/bin/env bash
# One-off (developer machine): subset the faces the GitHub assets embed into src/fonts.mjs as base64 WOFF2.
# Needs fonttools + brotli (python3 -m venv v && v/bin/pip install fonttools brotli) and the SGI files in apps/admin/public/fonts.
# The result is committed, so builds and CI need neither Python nor the source fonts.
# Glyph set: Basic Latin plus a few typographic marks. Anything else in a title falls back to the system font stack.
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"; fonts="$here/../../apps/admin/public/fonts"
py="${PYTHON:-python3}"; tmp="$(mktemp -d)"
U="U+0020-007E,U+00A0,U+00B7,U+00A9,U+2013,U+2014,U+2018,U+2019,U+201C,U+201D,U+2026,U+2192,U+2022"
sub() { "$py" -m fontTools.subset "$1" --unicodes="$U" --flavor=woff2 --layout-features="${LF:-kern}" --no-hinting --desubroutinize --output-file="$2"; }
sub "$fonts/sgi-text-800.woff2" "$tmp/title.woff2"
sub "$fonts/sgi-text-400.woff2" "$tmp/body.woff2"
"$py" -m fontTools.varLib.instancer "$fonts/jetbrains-mono.woff2" wght=500 -o "$tmp/mono-inst.woff2" >/dev/null
sub "$tmp/mono-inst.woff2" "$tmp/mono.woff2"
node -e '
const fs=require("fs"),d=process.argv[1];
const b=n=>fs.readFileSync(d+"/"+n+".woff2").toString("base64");
fs.writeFileSync(process.argv[2],`// Generated by scripts/subset-fonts.sh: Basic Latin subsets, base64 WOFF2. Do not edit by hand.
// SGI Text is a proprietary Bitstream typeface embedded with the owner'"'"'s consent; JetBrains Mono is SIL OFL 1.1.
export const FONT_DATA = {
  title: { family: "SGI Text", weight: 800, data: "${b("title")}" },
  body: { family: "SGI Text", weight: 400, data: "${b("body")}" },
  mono: { family: "JetBrains Mono", weight: 500, data: "${b("mono")}" },
};
`)' "$tmp" "$here/src/fonts.mjs"
rm -rf "$tmp"; wc -c "$here/src/fonts.mjs"
