// More retro hardware, drawn from photographs. Same method as machines.ts: a network of edges walked by
// trace(), so each drawing stays one unbroken stroke. Edges join where their end points coincide, which is
// why long lines are written as chains of short ones.
const chain = (pts: string[]) => pts.slice(1).map((p, i) => `${pts[i]} ${p}`);
const xs = (y: number, list: number[]) => chain(list.map((x) => `${x},${y}`));
const ys = (x: number, list: number[]) => chain(list.map((y) => `${x},${y}`));
const range = (a: number, b: number, step: number) => Array.from({ length: Math.floor((b - a) / step) + 1 }, (_, i) => a + i * step);
// Open path through the given vertices with every interior corner rounded to radius r. The extra waypoint
// 2r from each corner keeps the long sides straight; the one on the fillet keeps the corner round.
const rpath = (v: [number, number][], r: number) =>
  v.map(([x, y], i) => {
    if (i === 0 || i === v.length - 1) return `${x},${y}`;
    const dir = (a: [number, number], b: [number, number]) => { const l = Math.hypot(b[0] - a[0], b[1] - a[1]); return [(b[0] - a[0]) / l, (b[1] - a[1]) / l]; };
    const din = dir(v[i - 1], v[i]), dout = dir(v[i], v[i + 1]);
    const at = (d: number[], k: number) => `${(x + d[0] * k).toFixed(1)},${(y + d[1] * k).toFixed(1)}`;
    const mid = `${(x + (dout[0] - din[0]) * r * 0.293).toFixed(1)},${(y + (dout[1] - din[1]) * r * 0.293).toFixed(1)}`;
    return `${at(din, -2 * r)} ${at(din, -r)} ${mid} ${at(dout, r)} ${at(dout, 2 * r)}`;
  }).join(" ");
// A CRT face hanging from (x, y) on the case top by a short tick.
const tube = (x: number, y: number, x1: number, y1: number, x2: number, y2: number, r = 9) => [
  `${x},${y} ${x},${y1}`,
  rpath([[x, y1], [x1, y1], [x1, y2], [x2, y2], [x2, y1], [x, y1]], r),
];

