const f = (n: number) => String(Math.round(n * 10) / 10);
const chain = (pts: string[]) => pts.slice(1).map((p, i) => `${pts[i]} ${p}`);

// Ring or arc that alternates between two radii. sharp = spikes (blossom), otherwise scallops (frill).
const scallop = (cx: number, cy: number, r1: number, r2: number, a0: number, sweep: number, n: number, sharp = false) =>
  Array.from({ length: n * 2 + 1 }, (_, i) => {
    const t = ((a0 + (sweep * i) / (n * 2)) * Math.PI) / 180, r = i % 2 ? r2 : r1;
    return `${f(cx + r * Math.cos(t))},${f(cy + r * Math.sin(t))}${sharp ? "!" : ""}`;
  }).join(" ");

// Saw-toothed leaf: out along one edge of the midrib, round the tip, back along the other edge.
const serrated = (x0: number, y0: number, x1: number, y1: number, w: number, n: number) => {
  const dx = x1 - x0, dy = y1 - y0, len = Math.hypot(dx, dy), nx = -dy / len, ny = dx / len;
  const side = (s: number, k: number) => {
    const t = k / (n * 2), bulge = w * Math.sin(Math.PI * Math.min(1, t * 1.1)) * (k % 2 ? 1 : 0.45);
    return `${f(x0 + dx * t + nx * bulge * s)},${f(y0 + dy * t + ny * bulge * s)}!`;
  };
  const out: string[] = [];
  for (let k = 1; k < n * 2; k++) out.push(side(1, k));
  out.push(`${x1},${y1}!`);
  for (let k = n * 2 - 1; k >= 1; k--) out.push(side(-1, k));
  return out.join(" ");
};

