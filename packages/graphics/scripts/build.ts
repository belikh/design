// Writes dist/: one .svg per graphic, a <symbol> sprite, a manifest, a tiny JS module and the CSS.
// Then re-reads every file and enforces the style mechanically; a failure stops the build.
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { GRAPHICS, TIERS, pathAttrs, svg, type Tier } from "../src/index.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dist = join(root, "dist");
const version = JSON.parse(readFileSync(join(root, "package.json"), "utf8")).version as string;
const tiers = Object.keys(TIERS) as Tier[];

for (const tier of tiers) mkdirSync(join(dist, "svg", tier), { recursive: true });
for (const g of GRAPHICS) writeFileSync(join(dist, "svg", g.tier, `${g.name}.svg`), svg(g));

const sprite =
  `<svg xmlns="http://www.w3.org/2000/svg" style="display:none">\n` +
  GRAPHICS.map((g) => `<symbol id="jp-${g.id}" viewBox="0 0 ${TIERS[g.tier].w} ${TIERS[g.tier].h}"><path ${pathAttrs(g.tier)} d="${g.d}"/></symbol>`).join("\n") +
  `\n</svg>\n`;
writeFileSync(join(dist, "jupiter-graphics.svg"), sprite);

const manifest = { version, tiers: TIERS, graphics: GRAPHICS };
writeFileSync(join(dist, "manifest.json"), JSON.stringify(manifest, null, 1) + "\n");

writeFileSync(join(dist, "index.js"), `// Generated by scripts/build.ts. Do not edit.
export const VERSION = ${JSON.stringify(version)};
export const TIERS = ${JSON.stringify(TIERS)};
export const GRAPHICS = ${JSON.stringify(GRAPHICS)};
const byId = new Map(GRAPHICS.map((g) => [g.id, g]));
export const graphic = (id) => byId.get(id);
export function svg(id, opts = {}) {
  const g = byId.get(id);
  if (!g) throw new Error("unknown graphic: " + id);
  const t = TIERS[g.tier];
  const a11y = opts.title ? 'role="img" aria-label="' + String(opts.title).replace(/[<>&"]/g, "") + '"' : 'aria-hidden="true"';
  const cls = "jp-line jp-line--" + g.tier + (opts.class ? " " + opts.class : "");
  return '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ' + t.w + " " + t.h + '" class="' + cls + '" ' + a11y +
    '><path fill="none" stroke="currentColor" stroke-width="' + (opts.strokeWidth ?? t.stroke) +
    '" stroke-linecap="round" stroke-linejoin="round" pathLength="1" d="' + g.d + '"/></svg>';
}
`);
writeFileSync(join(dist, "index.d.ts"), `export type Tier = ${tiers.map((t) => `"${t}"`).join(" | ")};
export type Graphic = { id: string; tier: Tier; name: string; tags: string[]; d: string };
export declare const VERSION: string;
export declare const TIERS: Record<Tier, { w: number; h: number; stroke: number; pad: number; use: string }>;
export declare const GRAPHICS: Graphic[];
export declare function graphic(id: string): Graphic | undefined;
/** Inline SVG markup for a graphic id such as "spot-kangaroo". Colour comes from the surrounding text. */
export declare function svg(id: string, opts?: { title?: string; class?: string; strokeWidth?: number }): string;
`);

writeFileSync(join(dist, "jupiter-graphics.css"), `/* @belikh/jupiter-graphics ${version}. Every graphic is one stroke in currentColor: set color, not fill. */
@layer jupiter {
  .jp-line { display: inline-block; width: 1em; height: auto; vertical-align: -0.125em; color: inherit; overflow: visible; flex: none; }
  .jp-line--icon { width: var(--jp-line-icon, 1.5em); aspect-ratio: 1; }
  .jp-line--spot { width: var(--jp-line-spot, 15rem); max-width: 100%; aspect-ratio: 1; }
  .jp-line--scene { width: 100%; aspect-ratio: 2; }
  .jp-line--rule { display: block; width: 100%; aspect-ratio: 10; }
  /* Keep the hand the same weight at any rendered size. */
  .jp-line--hairline path { vector-effect: non-scaling-stroke; stroke-width: var(--jp-line-weight, 1.5px); }
  /* Draw the line on. Works for any graphic because every path has pathLength="1". */
  .jp-line--draw path { stroke-dasharray: 1; stroke-dashoffset: 1; animation: jp-line-draw var(--jp-line-duration, 2.4s) var(--jp-line-ease, cubic-bezier(0.6, 0, 0.2, 1)) var(--jp-line-delay, 0s) forwards; }
  .jp-line--loop path { animation-iteration-count: infinite; animation-direction: alternate; }
  @keyframes jp-line-draw { to { stroke-dashoffset: 0; } }
  @media (prefers-reduced-motion: reduce) { .jp-line--draw path { animation: none; stroke-dashoffset: 0; } }
}
`);

// ---- the style gate ----
const errors: string[] = [];
const names = new Set<string>();
for (const tier of tiers) {
  const t = TIERS[tier];
  for (const file of readdirSync(join(dist, "svg", tier))) {
    const src = readFileSync(join(dist, "svg", tier, file), "utf8"), id = `${tier}/${file}`;
    const bad = (why: string) => errors.push(`${id}: ${why}`);
    if (!/^[a-z0-9]+(-[a-z0-9]+)*\.svg$/.test(file)) bad("file name must be kebab-case");
    if (names.has(id)) bad("duplicate name");
    names.add(id);
    if ((src.match(/<path\b/g) ?? []).length !== 1) bad("must contain exactly one <path>");
    if (/<(circle|rect|line|polyline|polygon|ellipse|use|g|text|image)\b/.test(src)) bad("only a single <path> is allowed");
    const d = /\sd="([^"]+)"/.exec(src)?.[1] ?? "";
    if ((d.match(/[Mm]/g) ?? []).length !== 1 || /[Zz]/.test(d)) bad("the path must be one unbroken subpath (one M, no Z)");
    if (!src.includes(`viewBox="0 0 ${t.w} ${t.h}"`)) bad(`viewBox must be 0 0 ${t.w} ${t.h}`);
    if (!src.includes(`fill="none"`) || (src.match(/fill=/g) ?? []).length !== 1) bad("fill must be none");
    if (!src.includes(`stroke="currentColor"`) || /#[0-9a-f]{3,8}\b|rgb\(|hsl\(/i.test(src)) bad("colour must be currentColor only");
    if (!src.includes(`stroke-width="${t.stroke}"`)) bad(`stroke-width must be ${t.stroke}`);
    if (!src.includes(`stroke-linecap="round"`) || !src.includes(`stroke-linejoin="round"`)) bad("caps and joins must be round");
  }
}
if (new Set(GRAPHICS.map((g) => g.id)).size !== GRAPHICS.length) errors.push("duplicate graphic id");
if (errors.length) { console.error(errors.join("\n")); process.exit(1); }
console.log(`graphics ${version}: ${tiers.map((t) => `${GRAPHICS.filter((g) => g.tier === t).length} ${t}`).join(", ")}; style gate passed`);
