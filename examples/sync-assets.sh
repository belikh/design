#!/usr/bin/env bash
# Copy the generated theme + graphics into the demos so they always show what the build produces.
#   npm run build -w @belikh/jupiter-tokens -w @belikh/jupiter-graphics && examples/sync-assets.sh
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"; root="$here/.."
tok="$root/packages/tokens/dist"; gfx="$root/packages/graphics/dist/svg"; fonts="$root/packages/latex/fonts"
[ -f "$tok/jupiter.slint" ] || { echo "run: npm run build -w @belikh/jupiter-tokens" >&2; exit 1; }
[ -d "$gfx" ] || { echo "run: npm run build -w @belikh/jupiter-graphics" >&2; exit 1; }

# Slint
cp "$tok/jupiter.slint" "$here/slint/ui/jupiter.slint"
rm -rf "$here/slint/ui/assets" && mkdir -p "$here/slint/ui/assets" && cp -r "$gfx"/* "$here/slint/ui/assets/"
# Fonts are proprietary + gitignored: import whichever exist, otherwise Slint falls back to system fonts.
rm -rf "$here/slint/ui/fonts" && mkdir -p "$here/slint/ui/fonts"
{ echo "// Generated by sync-assets.sh. Imports bundled fonts when present."
  for f in sgi-text-400.otf sgi-text-700.otf jetbrains-mono-400.ttf; do
    [ -f "$fonts/$f" ] && { cp "$fonts/$f" "$here/slint/ui/fonts/$f"; echo "import \"fonts/$f\";"; }
  done
  echo "export component FontsLoaded {}"; } > "$here/slint/ui/fonts.slint"

# GTK
cp "$tok/jupiter-gtk-light.css" "$tok/jupiter-gtk-dark.css" "$tok/jupiter-gtk-widgets.css" "$here/gtk/assets/"
rm -rf "$here/gtk/assets/svg" && mkdir -p "$here/gtk/assets/svg" && cp -r "$gfx"/* "$here/gtk/assets/svg/"
echo "synced: slint/ui, gtk/assets"
